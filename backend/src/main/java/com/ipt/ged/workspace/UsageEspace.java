package com.ipt.ged.workspace;

/**
 * Usage d'un espace (R-03, décision D12).
 * METIER : organisation gérée par les gestionnaires d'espaces.
 * ECHANGE : espace de partage simple, les membres habilités y créent librement
 * dossiers et sous-dossiers et y déposent ; aucune édition en ligne.
 */
public enum UsageEspace {
    METIER,
    ECHANGE
}
